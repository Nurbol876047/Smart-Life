"""Еркін мәтінді (қазақша/орысша/аралас) операция(лар)ға талдау — NL → JSON."""

from __future__ import annotations

from .categories import categories_prompt_block
from .client import generate_json
from .schemas import ParseTransactionResult


def _build_prompt(text: str) -> str:
    return (
        "Сен — қаржылық көмекшінің мәтінді операцияға талдау модулісің.\n"
        "Пайдаланушы жазған еркін мәтінді (қазақша, орысша немесе аралас) "
        "кіріс/шығыс операцияларына бөл.\n\n"
        f"Санаттар (category өрісіне тек осы id-лерді қолдан):\n{categories_prompt_block()}\n\n"
        "Ережелер:\n"
        "- Бір мәтінде бірнеше бөлек операция болуы мүмкін "
        '(мыс. "такси 1500, кофе 800" — 2 операция). Бір затты сипаттайтын '
        'тізбекті бір операция ретінде қалдыр (мыс. "нан, сүт алдым 4500-ге" — 1 операция).\n'
        '- Сома жазылу түрлері: "450к"/"450k" = 450000, "1,5 млн"/"1.5 млн" = 1500000, '
        '"2 800" = 2800 (сан ішіндегі бос орын — мыңдық бөлгіш).\n'
        '- Күн сөздері: "кеше"/"вчера" = бүгіннен 1 күн бұрын, "бүгін"/"сегодня" = бүгін, '
        "күн көрсетілмесе — бүгін. Нәтижені YYYY-MM-DD пішінінде бер.\n"
        "- note өрісіне пайдаланушының өз тілінде қысқа сипаттама жаз "
        '(мыс. "такси", "нан, сүт").\n'
        "- confidence — сома мен санат қаншалықты анық болса, соғұрлым жоғары (0-1 аралығы).\n"
        "- Мәтінде НАҚТЫ сома көрсетілмеген операцияны мүлдем қоспа — "
        "сома ойлап тапба, бос тізім қайтар.\n\n"
        f'Талданатын мәтін: "{text}"'
    )


def parse_transaction_text(text: str) -> ParseTransactionResult:
    return generate_json(_build_prompt(text), ParseTransactionResult)
